import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { debounce } from "./debounce";

describe('debounce', () => {
    beforeEach(() => {
        vi.useFakeTimers()
    })
    afterEach(() => {
        vi.useRealTimers()
    })
    it('즉시 실행되지 않는다', () => {
        const fn = vi.fn()
        const debounced = debounce(fn, 300)
        debounced()
        expect(fn).not.toHaveBeenCalled()
    })
    it('ms가 지나면 실행된다', () => {
        const fn = vi.fn()
        const debounced = debounce(fn, 300)
        debounced()
        vi.advanceTimersByTime(300)
        expect(fn).toHaveBeenCalled()
    })
    it('ms가 덜 지나면 실행되지 않는다', () => {
        const fn = vi.fn()
        const debounced = debounce(fn, 300)
        debounced()
        vi.advanceTimersByTime(299)
        expect(fn).not.toHaveBeenCalled()
    })
    it('인자를 그대로 넘긴다', () => {
        const fn = vi.fn()
        const debounced = debounce(fn, 300)
        debounced('hello')
        vi.advanceTimersByTime(300)
        expect(fn).toHaveBeenCalledWith('hello')
    })
    it('연속 호출하면 마지막 것만 호출된다', () => {
        const fn = vi.fn()
        const debounced = debounce(fn, 300)
        debounced('a')
        vi.advanceTimersByTime(100)
        debounced('b')
        vi.advanceTimersByTime(100)
        debounced('c')
        vi.advanceTimersByTime(300)
        expect(fn).not.toHaveBeenCalledWith('a')
        expect(fn).not.toHaveBeenCalledWith('b')
        expect(fn).toHaveBeenCalledWith('c')
        expect(fn).toHaveBeenCalledTimes(1)
    })
    it('실행된 뒤에는 다시 시작한다', () => {
        const fn = vi.fn()
        const debounced = debounce(fn, 300)
        debounced('a')
        vi.advanceTimersByTime(300)
        debounced('b')
        vi.advanceTimersByTime(300)
        expect(fn).toHaveBeenCalledTimes(2)
    })
    it('취소할 수 있다', () => {
        const fn = vi.fn()
        const debounced = debounce(fn, 300)
        debounced()
        vi.advanceTimersByTime(100)
        debounced.cancel()
        vi.advanceTimersByTime(300)
        expect(fn).not.toHaveBeenCalled()
    })
    it('원본 함수의 인자 타입을 잃지 않는다', () => {
        const fn: (n: number | undefined) => void = vi.fn()
        const debounced = debounce(fn, 300)
        debounced()
        debounced(123)
        // @ts-expect-error string은 받으면 안 된다
        debounced('abc')
        // @ts-expect-error null은 받으면 안 된다
        debounced(null)
    })
    it('leading 모드에서 첫 호출은 즉시 실행하고, 이후 ms 동안은 무시한다', () => {
        const fn = vi.fn()
        const debounced = debounce(fn, 300, { leading: true })
        debounced('a')
        expect(fn).toHaveBeenCalledWith('a')
        vi.advanceTimersByTime(100)
        debounced('b')
        vi.advanceTimersByTime(300)
        expect(fn).not.toHaveBeenCalledWith('b')
        expect(fn).toHaveBeenCalledTimes(1)
    })
    it('leading 모드에서 ms가 지난 뒤의 첫 호출은 다시 즉시 실행한다', () => {
        const fn = vi.fn()
        const debounced = debounce(fn, 300, { leading: true })
        debounced('a')
        vi.advanceTimersByTime(300)
        debounced('b')
        expect(fn).toHaveBeenNthCalledWith(2, 'b')
        expect(fn).toHaveBeenCalledTimes(2)
    })
    it('cancel 뒤 leading 호출은 다시 즉시 실행된다', () => {
        const fn = vi.fn()
        const debounced = debounce(fn, 300, { leading: true })
        debounced('a')
        debounced.cancel()
        debounced('b')
        expect(fn).toHaveBeenNthCalledWith(2, 'b')
        expect(fn).toHaveBeenCalledTimes(2)
    })
    it('cancel 뒤의 호출은 이전 호출이 예약한 타이머에 영향받지 않는다', () => {
        const fn = vi.fn()
        const debounced = debounce(fn, 300, { leading: true })
        debounced('a')
        vi.advanceTimersByTime(100)
        debounced.cancel()
        debounced('b')
        vi.advanceTimersByTime(250)
        debounced('c')
        expect(fn).not.toHaveBeenCalledWith('c')
        expect(fn).toHaveBeenCalledTimes(2)
    })
    it('flush로 대기 중인 호출을 즉시 실행시킨다', () => {
        const fn = vi.fn()
        const debounced = debounce(fn, 300)
        debounced('a')
        debounced.flush()
        expect(fn).toHaveBeenCalledWith('a')
        expect(fn).toHaveBeenCalledTimes(1)
    })
    it('flush 이후 다시 호출할 수 있다', () => {
        const fn = vi.fn()
        const debounced = debounce(fn, 300)
        debounced('a')
        debounced.flush()
        debounced('b')
        vi.advanceTimersByTime(300)
        expect(fn).toHaveBeenNthCalledWith(2, 'b')
        expect(fn).toHaveBeenCalledTimes(2)
    })
    it('flush 이후 다시 호출했을 때, ms 동안은 무시한다', () => {
        const fn = vi.fn()
        const debounced = debounce(fn, 300)
        debounced('a')
        debounced.flush()
        debounced('b')
        vi.advanceTimersByTime(100)
        expect(fn).not.toHaveBeenCalledWith('b')
        expect(fn).toHaveBeenCalledTimes(1)
    })
    it('flush 뒤 ms가 지나도 다시 실행되지 않는다', () => {
        const fn = vi.fn()
        const debounced = debounce(fn, 300)
        debounced('a')
        debounced.flush()
        vi.advanceTimersByTime(300)
        expect(fn).toHaveBeenCalledWith('a')
        expect(fn).toHaveBeenCalledTimes(1)
    })
    it('flush를 두 번 해도 한 번만 실행된다', () => {
        const fn = vi.fn()
        const debounced = debounce(fn, 300)
        debounced('a')
        debounced.flush()
        debounced.flush()
        expect(fn).toHaveBeenCalledWith('a')
        expect(fn).toHaveBeenCalledTimes(1)
    })
    it('leading 모드에서는 flush가 다시 실행되지 않는다', () => {
        const fn = vi.fn()
        const debounced = debounce(fn, 300, { leading: true })
        debounced('a')
        debounced.flush()
        expect(fn).toHaveBeenCalledWith('a')
        expect(fn).toHaveBeenCalledTimes(1)
    })
})
